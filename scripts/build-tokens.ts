import StyleDictionary from "style-dictionary";
import { colorHex } from "../packages/theme/src/contrast.ts";
import { readFile, writeFile } from "node:fs/promises";
const themes = ["tamer-sabry-default", "navy-gold", "navy-cyan", "amun-light"];
StyleDictionary.registerFormat({
  name: "amun/css",
  format: ({ dictionary, options }) => {
    const selector = `[data-theme="${options.theme}"]`;
    return (
      selector +
      " {\n" +
      dictionary.allTokens
        .map((token) => {
          const value = token.$value;
          let css: string;
          if (token.$type === "color") css = colorHex(value);
          else if (token.$type === "fontFamily" && Array.isArray(value))
            css = value.map((font: string) => JSON.stringify(font)).join(", ");
          else if (
            token.$type === "dimension" &&
            value &&
            typeof value === "object"
          )
            css = String(value.value) + value.unit;
          else throw Error("Unsupported design token");
          return `  --amun-${token.path.join("-")}: ${css};`;
        })
        .join("\n") +
      "\n}\n"
    );
  },
});
const output: string[] = [];
for (const theme of themes) {
  const own = JSON.parse(await readFile(`tokens/${theme}.json`, "utf8"));
  if (own.safety) throw Error("Themes cannot override safety tokens");
  const dictionary = new StyleDictionary({
    usesDtcg: true,
    source: [
      `tokens/${theme}.json`,
      "tokens/safety.json",
      "tokens/common.json",
    ],
    platforms: {
      css: {
        transforms: ["name/kebab"],
        files: [
          {
            destination: `${theme}.css`,
            format: "amun/css",
            options: { theme },
          },
        ],
      },
    },
  });
  const files = await dictionary.formatPlatform("css");
  output.push(String(files[0]?.output ?? ""));
}
await writeFile(
  "apps/renderer/src/tokens.css",
  "/* Generated by Style Dictionary; edit tokens/*.json. */\n" +
    output.join("\n"),
);
